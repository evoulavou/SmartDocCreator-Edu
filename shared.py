def has_data(val) -> bool:
    """True αν η τιμή δεν είναι κενή / NaN / '-'."""
    return pd.notna(val) and str(val).strip() not in ('', 'nan', '-')


def load_general_info(df: dict) -> dict[str, str]:
    """
    Διαβάζει το sheet 'Στοιχεία απόφασης' και επιστρέφει dict
    {search_term: value} για όλα τα SEARCH_TERMS.
    """
    replacements: dict[str, str] = {}
    if 'Στοιχεία απόφασης' not in df:
        return replacements
    info_data = df['Στοιχεία απόφασης'].set_index(0)
    for term in SEARCH_TERMS:
        try:
            replacements[term] = str(info_data.loc[term].iloc[0])
        except KeyError:
            print(f"Warning: '{term}' not found in 'Στοιχεία απόφασης'")
    return replacements

def _find_libreoffice() -> str | None:
    lo = shutil.which('libreoffice') or shutil.which('soffice')
    if lo:
        return lo
    win_paths = [
        r"C:\Program Files\LibreOffice\program\soffice.exe",
        r"C:\Program Files (x86)\LibreOffice\program\soffice.exe",
    ]
    return next((p for p in win_paths if os.path.exists(p)), None)


def convert_to_pdf(folder_path: str) -> None:
    """Μετατρέπει όλα τα .docx στο φάκελο σε PDF."""
    lo_path = _find_libreoffice()
    docx_files = [f for f in os.listdir(folder_path) if f.endswith('.docx')]

    if lo_path:
        for filename in docx_files:
            subprocess.run(
                [lo_path, '--headless', '--convert-to', 'pdf', '--outdir', folder_path,
                 os.path.join(folder_path, filename)],
                check=True,
            )
        print("Conversion done using LibreOffice.")
        return

    try:
        from docx2pdf import convert
        for filename in docx_files:
            doc_path = os.path.join(folder_path, filename)
            convert(doc_path, doc_path.replace('.docx', '.pdf'))
        print("Conversion done using docx2pdf.")
    except ImportError:
        print("Neither LibreOffice nor docx2pdf is available.")
    except Exception as exc:
        print(f"docx2pdf failed: {exc}")
